"""Detect the 12 packed animation frames in each horse_N_a.png and emit TS rects."""
from PIL import Image
import json

PUB = "/Users/masterdee/horse-racing-clone/public/sprites"


def blobs(im):
    a = im.split()[3]
    W, H = im.size
    px = a.load()
    seen = bytearray(W * H)
    out = []
    for y in range(H):
        for x in range(W):
            if px[x, y] > 10 and not seen[y * W + x]:
                # flood fill
                stack = [(x, y)]
                seen[y * W + x] = 1
                minx = maxx = x
                miny = maxy = y
                n = 0
                while stack:
                    cy, cx = stack.pop()
                    n += 1
                    if cx < minx:
                        minx = cx
                    if cx > maxx:
                        maxx = cx
                    if cy < miny:
                        miny = cy
                    if cy > maxy:
                        maxy = cy
                    for dy in (-1, 0, 1):
                        for dx in (-1, 0, 1):
                            ny, nx = cy + dy, cx + dx
                            if 0 <= ny < H and 0 <= nx < W and px[nx, ny] > 10 and not seen[ny * W + nx]:
                                seen[ny * W + nx] = 1
                                stack.append((ny, nx))
                if n > 200:
                    out.append((minx, miny, maxx + 1, maxy + 1))
    return out


all_frames = {}
for n in range(1, 9):
    im = Image.open(f"{PUB}/horse_{n}_a.png").convert("RGBA")
    bb = blobs(im)
    # grid-sort: 4 rows by y-center, then 3 cols by x-center
    bb.sort(key=lambda b: (b[1] + b[3]) / 2)
    rows = []
    for b in bb:
        cy = (b[1] + b[3]) / 2
        placed = False
        for r in rows:
            if abs((r[0][1] + r[0][3]) / 2 - cy) < 60:
                r.append(b)
                placed = True
                break
        if not placed:
            rows.append([b])
    frames = []
    for r in rows:
        r.sort(key=lambda b: (b[0] + b[2]) / 2)
        frames.extend(r)
    assert len(frames) == 12, f"horse {n}: found {len(frames)} frames"
    # pad slightly
    frames = [
        [max(0, x0 - 3), max(0, y0 - 3), min(1024, x1 + 3), min(1024, y1 + 3)]
        for (x0, y0, x1, y1) in frames
    ]
    all_frames[n] = frames
    print(n, frames[0], "...", frames[-1])

ts = "// Auto-generated by scripts/frames.py — packed _a sprite rects (12 per horse).\n"
ts += "export const HORSE_A_FRAMES: Record<number, Array<[number, number, number, number]>> = {\n"
for n in range(1, 9):
    ts += f"  {n}: [{', '.join(str(f) for f in all_frames[n])}],\n"
ts += "};\n"
with open("/Users/masterdee/horse-racing-clone/src/game/horseFrames.ts", "w") as f:
    f.write(ts)
print("written")
